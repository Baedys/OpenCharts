using System;
using System.Collections.Generic;

namespace OpenSlideCharts
{
    public sealed class WaterfallCommandResult
    {
        public string ConnectorId, PinId, ReleasedAutoPinId;
        public List<string> AffectedPinIds = new List<string>();
        public WaterfallSolution Solution;
    }

    public sealed class WaterfallCommandAnalysis
    {
        public bool StrictSucceeds;
        public WaterfallSolveFailure? StrictFailure;
        // Every listed ID independently permits a complete solution when that
        // one generated pin is removed. The caller must choose explicitly.
        public List<string> AutoPinIds = new List<string>();
    }

    // Original command policy, not inferred vendor behavior. Commands first
    // retain all pins. Only after a constraint failure may an explicitly named
    // generated pin be removed; other manual pins are never removed or changed.
    // PinZero explicitly edits all existing equations for its exact target
    // anchor to zero, preserving their IDs and marking them manual.
    // Analysis and failed commands leave the supplied model untouched.
    public static class WaterfallCommands
    {
        private sealed class Prepared
        {
            internal WaterfallSpec Model;
            internal WaterfallCommandResult Result = new WaterfallCommandResult();
        }

        public static WaterfallCommandResult AddConnector(WaterfallSpec model, WaterfallAnchor left,
            WaterfallAnchor right, bool constrain = true, string autoPinIdToRelease = null)
        {
            return Execute(model, PrepareConnector(model, left, right, constrain), autoPinIdToRelease);
        }

        public static WaterfallCommandResult PinZero(WaterfallSpec model, WaterfallAnchor anchor,
            string autoPinIdToRelease = null)
        {
            return Execute(model, PreparePin(model, anchor), autoPinIdToRelease);
        }

        public static WaterfallCommandAnalysis AnalyzeAddConnector(WaterfallSpec model, WaterfallAnchor left,
            WaterfallAnchor right, bool constrain = true)
        {
            return Analyze(PrepareConnector(model, left, right, constrain));
        }

        public static WaterfallCommandAnalysis AnalyzePinZero(WaterfallSpec model, WaterfallAnchor anchor)
        {
            return Analyze(PreparePin(model, anchor));
        }

        private static Prepared PrepareConnector(WaterfallSpec model, WaterfallAnchor left, WaterfallAnchor right, bool constrain)
        {
            WaterfallSpec copy = CopyCollections(model);
            WaterfallAnchor source = WaterfallInteraction.CopyAnchor(left), target = WaterfallInteraction.CopyAnchor(right);
            foreach (WaterfallConnector existing in copy.Connectors)
            {
                if (existing.Constrain != constrain) continue;
                if (WaterfallInteraction.SameAnchor(existing.Left, source) && WaterfallInteraction.SameAnchor(existing.Right, target) ||
                    WaterfallInteraction.SameAnchor(existing.Left, target) && WaterfallInteraction.SameAnchor(existing.Right, source))
                    throw new ArgumentException("A connector with the same unordered anchors and constraint mode already exists.");
            }
            string id;
            do { id = "link_" + Guid.NewGuid().ToString("N"); }
            while (copy.Connectors.Exists(delegate(WaterfallConnector edge) { return edge.Id == id; }));
            copy.Connectors.Add(new WaterfallConnector { Id = id, Left = source, Right = target, Constrain = constrain });
            return new Prepared { Model = copy, Result = new WaterfallCommandResult { ConnectorId = id } };
        }

        private static Prepared PreparePin(WaterfallSpec model, WaterfallAnchor anchor)
        {
            WaterfallSpec copy = CopyCollections(model);
            WaterfallAnchor target = WaterfallInteraction.CopyAnchor(anchor);
            WaterfallCommandResult result = new WaterfallCommandResult();
            // The command explicitly requests zero for this exact anchor.
            // Update every duplicate equation rather than retaining a hidden
            // conflicting level or discarding its stable identity.
            for (int i = 0; i < copy.Pins.Count; i++)
            {
                WaterfallPin pin = copy.Pins[i];
                if (!WaterfallInteraction.SameAnchor(pin.Anchor, target)) continue;
                copy.Pins[i] = new WaterfallPin { Id = pin.Id, Anchor = WaterfallInteraction.CopyAnchor(pin.Anchor), Level = 0, AutoGenerated = false };
                if (result.PinId == null) result.PinId = pin.Id;
                result.AffectedPinIds.Add(pin.Id);
            }
            if (result.PinId != null) return new Prepared { Model = copy, Result = result };
            string id;
            do { id = "pin_" + Guid.NewGuid().ToString("N"); }
            while (copy.Pins.Exists(delegate(WaterfallPin pin) { return pin.Id == id; }));
            copy.Pins.Add(new WaterfallPin { Id = id, Anchor = target, Level = 0, AutoGenerated = false });
            result.PinId = id; result.AffectedPinIds.Add(id);
            return new Prepared { Model = copy, Result = result };
        }

        private static WaterfallCommandResult Execute(WaterfallSpec original, Prepared prepared, string releaseId)
        {
            try { prepared.Result.Solution = WaterfallSolver.Solve(prepared.Model); }
            catch (WaterfallSolveException)
            {
                if (releaseId == null) throw;
                int at = prepared.Model.Pins.FindIndex(delegate(WaterfallPin pin) { return pin.Id == releaseId; });
                if (at < 0) throw new ArgumentException("The requested generated pin does not exist: " + releaseId);
                if (!prepared.Model.Pins[at].AutoGenerated)
                    throw new ArgumentException("Manual pins cannot be released by this command: " + releaseId);
                prepared.Model.Pins.RemoveAt(at);
                prepared.Result.Solution = WaterfallSolver.Solve(prepared.Model);
                prepared.Result.ReleasedAutoPinId = releaseId;
            }
            // Strict success takes priority: releaseId is ignored when no
            // removal is needed. Nothing is committed until solving succeeds.
            original.Connectors = prepared.Model.Connectors;
            original.Pins = prepared.Model.Pins;
            return prepared.Result;
        }

        private static WaterfallCommandAnalysis Analyze(Prepared prepared)
        {
            WaterfallCommandAnalysis analysis = new WaterfallCommandAnalysis();
            try
            {
                WaterfallSolver.Solve(prepared.Model);
                analysis.StrictSucceeds = true;
                return analysis;
            }
            catch (WaterfallSolveException error) { analysis.StrictFailure = error.Failure; }
            // Removing an equation cannot determine an underdetermined system.
            if (analysis.StrictFailure == WaterfallSolveFailure.Underdetermined) return analysis;
            for (int i = 0; i < prepared.Model.Pins.Count; i++)
            {
                WaterfallPin pin = prepared.Model.Pins[i];
                if (!pin.AutoGenerated) continue;
                WaterfallSpec candidate = CopyCollections(prepared.Model);
                candidate.Pins.RemoveAt(i);
                try
                {
                    WaterfallSolver.Solve(candidate);
                    analysis.AutoPinIds.Add(pin.Id);
                }
                catch (WaterfallSolveException) { }
                catch (ArgumentException)
                {
                    // A mathematically determined repair may exceed numeric
                    // rendering limits. Such a pin is not offered as viable.
                }
            }
            return analysis;
        }

        private static WaterfallSpec CopyCollections(WaterfallSpec model)
        {
            if (model == null || model.Columns == null || model.Connectors == null || model.Pins == null)
                throw new ArgumentException("Waterfall model and collections are required.");
            foreach (WaterfallConnector edge in model.Connectors) if (edge == null) throw new ArgumentException("Connectors cannot be null.");
            foreach (WaterfallPin pin in model.Pins) if (pin == null) throw new ArgumentException("Pins cannot be null.");
            // Existing entities are read-only during preparation. Any promoted
            // pin is replaced in this private list, never edited in place.
            return new WaterfallSpec
            {
                Columns = new List<WaterfallColumn>(model.Columns),
                Connectors = new List<WaterfallConnector>(model.Connectors),
                Pins = new List<WaterfallPin>(model.Pins),
                SegmentOrder = model.SegmentOrder, ShowSigns = model.ShowSigns
            };
        }
    }
}
