using System;
using System.Collections.Generic;
using OpenSlideCharts;

public static class WaterfallInteractionTests
{
    private static int scenarios, assertions;
    public static int Main()
    {
        try
        {
            Geometry(); TargetWeights(); SparseOrder(); HitTests(); ScaleExtremes(); DeleteStartsSum();
            LeftTotalDrag(); ManualPins(); Rollback(); SoftDelete(); UnresolvedEquals(); Validation();
            Console.WriteLine("PASS: " + scenarios + " waterfall interaction scenarios, " + assertions + " assertions");
            return 0;
        }
        catch (Exception ex) { Console.Error.WriteLine(ex); return 1; }
    }

    private static double?[] Row(params double?[] values) { return values; }
    private static WaterfallSpec Spec(params double?[][] rows)
    {
        WaterfallSpec result = new WaterfallSpec();
        for (int i = 0; i < rows.Length; i++)
        {
            WaterfallColumn column = new WaterfallColumn { Id = "c" + i, Label = "Category " + i };
            for (int j = 0; j < rows[i].Length; j++)
                column.Segments.Add(new WaterfallSegment { Id = "s" + i + "_" + j, Value = rows[i][j], Calculated = !rows[i][j].HasValue });
            result.Columns.Add(column);
        }
        return result;
    }
    private static WaterfallAnchor B(WaterfallSpec s,int i) { return WaterfallAnchor.AtBase(s.Columns[i]); }
    private static WaterfallAnchor O(WaterfallSpec s,int i) { return WaterfallAnchor.AtOutput(s.Columns[i]); }
    private static void Pin(WaterfallSpec s,WaterfallAnchor a,double level,bool auto)
    { s.Pins.Add(new WaterfallPin { Id = "p" + s.Pins.Count, Anchor = a, Level = level, AutoGenerated = auto }); }
    private static void Link(WaterfallSpec s,WaterfallAnchor a,WaterfallAnchor b)
    { s.Connectors.Add(new WaterfallConnector { Id = "edge" + s.Connectors.Count, Left = a, Right = b }); }
    private static void Forward(WaterfallSpec s)
    {
        for (int i=0;i<s.Columns.Count;i++)
        {
            bool e = s.Columns[i].Segments.Exists(delegate(WaterfallSegment segment) { return segment.Calculated; });
            if (i==0 || e) Pin(s,B(s,i),0,true);
            if (i>0) Link(s,O(s,i-1),e ? O(s,i) : B(s,i));
        }
    }
    private static WaterfallSpec Original()
    {
        WaterfallSpec s = Spec(Row(41),Row(35),Row(-12,-17),Row((double?)null),Row(-5),Row((double?)null)); Forward(s); return s;
    }
    private static WaterfallSpec EndAtZero()
    {
        WaterfallSpec s = Spec(Row((double?)null),Row(3),Row(2),Row(4));
        Pin(s,B(s,0),0,true); Pin(s,O(s,3),0,true);
        for (int i=1;i<4;i++) Link(s,O(s,i-1),B(s,i));
        return s;
    }
    private static void Geometry()
    {
        scenarios++;
        WaterfallScene scene = WaterfallScene.Build(Original(),640,360);
        Near(scene.Minimum,0); Near(scene.Maximum,76);
        Near(scene.PlotLeft,58); Near(scene.PlotTop,64); Near(scene.PlotWidth,558); Near(scene.PlotHeight,218);
        Near(scene.Step,93); Near(scene.BarWidth,57.66); Near(scene.MapY(0),282); Near(scene.MapY(76),64);
        Near(scene.Columns[0].X,75.67); Near(scene.Columns[0].Width,57.66);
        Near(scene.Columns[0].OutputY,282-218.0*41/76);
        Near(scene.Connectors[0].X1,133.33); Near(scene.Connectors[0].X2,168.67);
        Near(scene.Connectors[0].Y1,scene.Columns[0].OutputY); Near(scene.Connectors[0].Y2,scene.Columns[1].BaseY);
        foreach (WaterfallTarget target in scene.Targets)
        {
            Check(target.X>=58 && target.X<=616 && target.Y>=64 && target.Y<=282,"Target stays in plot");
            Check(target.Side=="Left" || target.Side=="Right","Known target side");
        }
    }
    private static void TargetWeights()
    {
        scenarios++;
        WaterfallSpec s=Spec(Row(3),Row(5,-2),Row((double?)null)); Forward(s);
        WaterfallScene scene=WaterfallScene.Build(s,640,360);
        CheckAllTargets(scene);
        WaterfallTarget sum=Target(scene,"c1",null,"Output","Right");
        Near(sum.Y,scene.MapY(6)); Check(sum.Anchor.Weights[0]==1 && sum.Anchor.Weights[1]==1,"Signed sum weights");
        WaterfallTarget positiveTop=Target(scene,"c1","s1_0","Top","Left");
        Check(positiveTop.Anchor.Weights[0]==1 && positiveTop.Anchor.Weights[1]==0,"Positive physical top differs from signed sum");
        WaterfallTarget negativeBottom=Target(scene,"c1","s1_1","Bottom","Left");
        Check(negativeBottom.Anchor.Weights[0]==0 && negativeBottom.Anchor.Weights[1]==1,"Negative physical bottom weights");
        Near(negativeBottom.Y,scene.MapY(1));
        // Every side owns independent anchor weights, suitable for UI copying.
        WaterfallTarget right=Target(scene,"c1","s1_0","Top","Right");
        positiveTop.Anchor.Weights[0]=0;
        Check(right.Anchor.Weights[0]==1,"Target anchors do not alias mutable weight lists");
    }
    private static void SparseOrder()
    {
        scenarios++;
        WaterfallSpec s=Spec(Row(4,3,-5,-2),Row(5),Row(2,null,-1));
        int[] rows={7,1,6,2};
        for(int i=0;i<4;i++)s.Columns[0].Segments[i].SheetRow=rows[i];
        Pin(s,B(s,0),0,true); Pin(s,B(s,1),0,true); Pin(s,B(s,2),0,true); Link(s,O(s,1),O(s,2));
        foreach(string order in new string[]{"SheetTopToBottom","SheetBottomToTop"})
        {
            s.SegmentOrder=order; CheckAllTargets(WaterfallScene.Build(s,640,360));
        }
        s.Columns[1].Segments[0].Value=-10;
        CheckAllTargets(WaterfallScene.Build(s,640,360)); // e crosses sign.
    }
    private static void HitTests()
    {
        scenarios++;
        WaterfallSpec s=Spec(Row(10)); Forward(s);
        WaterfallScene scene=WaterfallScene.Build(s,640,360);
        WaterfallTarget top=Target(scene,"c0",null,"Output","Left");
        WaterfallHit hit=scene.FindNearest(top.X,top.Y,0);
        Check(hit.Target!=null && !hit.IsAmbiguous && hit.Candidates.Count==1,"Equivalent output/top aliases collapsed");
        Near(hit.Distance,0);
        hit=scene.FindNearest(top.X,(scene.Columns[0].BaseY+scene.Columns[0].OutputY)/2,109);
        Check(hit.Target==null && hit.IsAmbiguous && hit.Candidates.Count==2,"Equidistant different anchors need explicit choice");
        hit=scene.FindNearest(-1000,-1000,1); Check(hit.Target==null && !hit.IsAmbiguous && hit.Candidates.Count==0,"No candidate outside tolerance");
        s=Spec(Row(0));Forward(s);scene=WaterfallScene.Build(s,640,360);
        hit=scene.FindNearest(scene.Columns[0].X,scene.MapY(0),0);
        Check(hit.IsAmbiguous && hit.Candidates.Count==2,"Zero segment preserves distinct symbolic base and output");
    }
    private static void ScaleExtremes()
    {
        scenarios++;
        foreach(double magnitude in new double[]{1e300,1e-300})
        {
            WaterfallSpec s=Spec(Row(magnitude,-magnitude));Forward(s);
            WaterfallScene scene=WaterfallScene.Build(s,640,360);
            Near(scene.MapY(magnitude),64); Near(scene.MapY(-magnitude),282); Near(scene.MapY(0),173);
            CheckAllTargets(scene);
        }
        WaterfallSpec z=Spec(Row(0));Forward(z);Near(WaterfallScene.Build(z,640,360).MapY(0),282);
    }
    private static void DeleteStartsSum()
    {
        scenarios++;
        WaterfallSpec s=Original();
        WaterfallEditResult result=WaterfallInteraction.DeleteConnector(s,"edge0");
        double[] levels={41,35,6,6,1,1};
        for(int i=0;i<levels.Length;i++)Near(result.Solution.Columns[i].Output,levels[i]);
        Check(result.AddedPinIds.Count==1 && result.RemovedPinIds.Count==0,"One new generated baseline for detached sum");
        Check(s.Pins.Exists(delegate(WaterfallPin p){return p.Id==result.AddedPinIds[0] && p.AutoGenerated;}),"Generated provenance retained");
        Check(s.Connectors.Count==4,"Connector deleted");
    }
    private static void LeftTotalDrag()
    {
        scenarios++;
        WaterfallSpec s=EndAtZero();Near(WaterfallSolver.Solve(s).Columns[0].Output,-9);
        WaterfallEditResult result=WaterfallInteraction.Reattach(s,"edge0",false,O(s,3));
        double[] levels={9,3,5,9};for(int i=0;i<4;i++)Near(result.Solution.Columns[i].Output,levels[i]);
        Check(result.RemovedPinIds.Count==1 && result.RemovedPinIds[0]=="p1","Only generated final output pin removed");
        Check(result.AddedPinIds.Count==1,"New numeric baseline added");
        Check(s.Pins.Exists(delegate(WaterfallPin p){return p.Id=="p0";}),"Calculated column baseline preserved");
        Check(WaterfallInteraction.SameAnchor(s.Connectors[0].Right,O(s,3)),"Moved endpoint persisted");
    }
    private static void ManualPins()
    {
        scenarios++;
        WaterfallSpec s=EndAtZero();s.Pins[1].AutoGenerated=false;
        WaterfallAnchor previous=s.Connectors[0].Right;List<WaterfallPin> pins=s.Pins;
        ExpectFailure(delegate{WaterfallInteraction.Reattach(s,"edge0",false,O(s,3));},WaterfallSolveFailure.Inconsistent);
        Check(Object.ReferenceEquals(s.Connectors[0].Right,previous) && Object.ReferenceEquals(s.Pins,pins),"Manual conflict restores graph");
        Check(!s.Pins[1].AutoGenerated,"Manual pin unchanged");Near(WaterfallSolver.Solve(s).Columns[0].Output,-9);
        s=Original();Pin(s,B(s,1),41,false);
        WaterfallEditResult result=WaterfallInteraction.DeleteConnector(s,"edge0");
        Near(result.Solution.Columns[1].Base,41);
        Check(result.AddedPinIds.Count==0,"Existing manual detached baseline retained");
    }
    private static void Rollback()
    {
        scenarios++;
        WaterfallSpec s=Original();WaterfallAnchor old=s.Connectors[0].Right;List<WaterfallPin> pins=s.Pins;
        ExpectArgument(delegate{WaterfallInteraction.Reattach(s,"edge0",false,WaterfallAnchor.ForWeights("missing",0));});
        Check(Object.ReferenceEquals(old,s.Connectors[0].Right) && Object.ReferenceEquals(pins,s.Pins),"Unknown target rolls back");
        ExpectArgument(delegate{WaterfallInteraction.Reattach(s,"unknown",false,O(s,1));});
        ExpectArgument(delegate{WaterfallInteraction.DeleteConnector(s,"unknown");});
        WaterfallEditResult unchanged=WaterfallInteraction.Reattach(s,"edge0",false,old);
        Check(unchanged.AddedPinIds.Count==0 && unchanged.RemovedPinIds.Count==0,"No-op reattach preserves pins");
        WaterfallAnchor target=O(s,1);
        // A free connector can move without changing any hard constraints.
        s.Connectors.Add(new WaterfallConnector{Id="free",Left=B(s,0),Right=B(s,1),Constrain=false});
        WaterfallInteraction.Reattach(s,"free",false,target);target.Weights[0]=0;
        Check(s.Connectors[s.Connectors.Count-1].Right.Weights[0]==1,"Reattach copies supplied anchor");
    }
    private static void SoftDelete()
    {
        scenarios++;
        WaterfallSpec s=Original();s.Connectors.Add(new WaterfallConnector{Id="free",Left=B(s,0),Right=B(s,1),Constrain=false});
        int count=s.Pins.Count;WaterfallEditResult result=WaterfallInteraction.DeleteConnector(s,"free");
        Check(s.Pins.Count==count && result.AddedPinIds.Count==0 && result.RemovedPinIds.Count==0,"Soft deletion never repairs hard graph");
    }
    private static void UnresolvedEquals()
    {
        scenarios++;
        WaterfallSpec s=Spec(Row(41),Row((double?)null));Forward(s);
        List<WaterfallConnector> before=s.Connectors;List<WaterfallPin> pins=s.Pins;
        ExpectFailure(delegate{WaterfallInteraction.DeleteConnector(s,"edge0");},WaterfallSolveFailure.Underdetermined);
        Check(Object.ReferenceEquals(before,s.Connectors) && Object.ReferenceEquals(pins,s.Pins),"Underdetermined edit rolls back instead of inventing e");
    }
    private static void Validation()
    {
        scenarios++;
        WaterfallSpec s=Original();
        ExpectArgument(delegate{WaterfallScene.Build(s,319,360);});ExpectArgument(delegate{WaterfallScene.Build(s,640,239);});
        ExpectArgument(delegate{WaterfallScene.Build(s,Double.NaN,360);});
        WaterfallScene scene=WaterfallScene.Build(s,640,360);
        ExpectArgument(delegate{scene.FindNearest(0,0,-1);});ExpectArgument(delegate{scene.FindNearest(Double.NaN,0,1);});
        ExpectArgument(delegate{scene.FindNearest(0,0,Double.PositiveInfinity);});ExpectArgument(delegate{scene.MapY(Double.NaN);});
    }
    private static WaterfallTarget Target(WaterfallScene s,string column,string segment,string edge,string side)
    {
        foreach(WaterfallTarget t in s.Targets)if(t.ColumnId==column && t.SegmentId==segment && t.Edge==edge && t.Side==side)return t;
        throw new Exception("Missing target");
    }
    private static void CheckAllTargets(WaterfallScene scene)
    {
        foreach(WaterfallTarget target in scene.Targets)
        {
            WaterfallColumnSolution column=scene.Solution.FindColumn(target.ColumnId);
            double level=column.Base;
            for(int i=0;i<target.Anchor.Weights.Count;i++)level+=target.Anchor.Weights[i]*column.Segments[i].Value;
            Near(scene.MapY(level),target.Y);
        }
    }
    private static void ExpectArgument(Action action)
    {try{action();}catch(ArgumentException){assertions++;return;}throw new Exception("Expected invalid argument");}
    private static void ExpectFailure(Action action,WaterfallSolveFailure failure)
    {try{action();}catch(WaterfallSolveException ex){Check(ex.Failure==failure,"Expected solve failure");return;}throw new Exception("Expected solve failure");}
    private static void Near(double actual,double expected)
    {Check(!Double.IsNaN(actual)&&!Double.IsInfinity(actual)&&Math.Abs(actual-expected)<1e-7,"Expected "+expected+", got "+actual);}
    private static void Check(bool condition,string message){assertions++;if(!condition)throw new Exception(message);}
}
