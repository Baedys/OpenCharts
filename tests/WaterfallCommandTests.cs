using System;
using System.Collections.Generic;
using OpenSlideCharts;

public static class WaterfallCommandTests
{
    private static int scenarios, assertions;
    public static int Main()
    {
        try
        {
            StrictAddition(); IndependentComponents(); MultipleRepairs(); ManualConflict(); PhysicalBaseline();
            ExistingPinEdits(); TargetedDuplicates(); EqualsStaySymbolic(); DuplicateConnectors(); FailedRelease();
            NoUnnecessaryRelease(); AnchorCopies(); CandidateRequiresCompleteSolution(); InvalidInputs();
            Console.WriteLine("PASS: " + scenarios + " waterfall command scenarios, " + assertions + " assertions"); return 0;
        }
        catch(Exception ex){Console.Error.WriteLine(ex);return 1;}
    }
    private static double?[] Row(params double?[] values){return values;}
    private static WaterfallSpec Spec(params double?[][] rows)
    {
        WaterfallSpec model=new WaterfallSpec();
        for(int i=0;i<rows.Length;i++)
        {
            WaterfallColumn column=new WaterfallColumn{Id="c"+i,Label="Column "+i};
            for(int j=0;j<rows[i].Length;j++)column.Segments.Add(new WaterfallSegment{Id="s"+i+"_"+j,Value=rows[i][j],Calculated=!rows[i][j].HasValue});
            model.Columns.Add(column);
        }
        return model;
    }
    private static WaterfallAnchor B(WaterfallSpec s,int i){return WaterfallAnchor.AtBase(s.Columns[i]);}
    private static WaterfallAnchor O(WaterfallSpec s,int i){return WaterfallAnchor.AtOutput(s.Columns[i]);}
    private static void Pin(WaterfallSpec s,WaterfallAnchor a,double level,bool auto)
    {s.Pins.Add(new WaterfallPin{Id="p"+s.Pins.Count,Anchor=a,Level=level,AutoGenerated=auto});}
    private static void Link(WaterfallSpec s,WaterfallAnchor a,WaterfallAnchor b)
    {s.Connectors.Add(new WaterfallConnector{Id="edge"+s.Connectors.Count,Left=a,Right=b});}
    private static void StrictAddition()
    {
        scenarios++;WaterfallSpec s=Spec(Row(3),Row(3));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,false);
        List<WaterfallConnector> links=s.Connectors;List<WaterfallPin> pins=s.Pins;
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),O(s,1));
        Check(analysis.StrictSucceeds && analysis.StrictFailure==null && analysis.AutoPinIds.Count==0,"Strict command needs no release");
        Check(Object.ReferenceEquals(links,s.Connectors) && Object.ReferenceEquals(pins,s.Pins),"Analysis does not replace collections");
        WaterfallColumn column=s.Columns[0];WaterfallSegment segment=column.Segments[0];
        WaterfallCommandResult result=WaterfallCommands.AddConnector(s,O(s,0),O(s,1));
        Check(s.Connectors.Count==1 && s.Connectors[0].Id==result.ConnectorId,"New stable connector ID returned");
        Check(Object.ReferenceEquals(column,s.Columns[0]) && Object.ReferenceEquals(segment,s.Columns[0].Segments[0]),"Column and segment identities preserved");
        Check(result.ReleasedAutoPinId==null && result.Solution.Connectors.Count==1,"Strict result published");
    }
    private static void IndependentComponents()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row(35));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,true);
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),B(s,1));
        Check(!analysis.StrictSucceeds && analysis.StrictFailure==WaterfallSolveFailure.Inconsistent,"Grounded sums initially conflict");
        Check(analysis.AutoPinIds.Count==1 && analysis.AutoPinIds[0]=="p1","Only target generated baseline is viable");
        ExpectFailure(delegate{WaterfallCommands.AddConnector(s,O(s,0),B(s,1));},WaterfallSolveFailure.Inconsistent);
        Check(s.Connectors.Count==0 && s.Pins.Count==2,"No implicit repair without explicit ID");
        WaterfallCommandResult result=WaterfallCommands.AddConnector(s,O(s,0),B(s,1),true,analysis.AutoPinIds[0]);
        Near(result.Solution.Columns[0].Output,41);Near(result.Solution.Columns[1].Base,41);Near(result.Solution.Columns[1].Output,76);
        Check(result.ReleasedAutoPinId=="p1" && s.Pins.Count==1 && s.Pins[0].Id=="p0","Only selected generated pin removed");
    }
    private static void MultipleRepairs()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row(35));Pin(s,B(s,0),0,true);Pin(s,B(s,1),0,true);
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),B(s,1));
        Check(analysis.AutoPinIds.Count==2 && analysis.AutoPinIds.Contains("p0") && analysis.AutoPinIds.Contains("p1"),"Both individually valid releases reported");
        Check(s.Pins.Count==2 && s.Connectors.Count==0,"Multiple choices do not choose silently");
        WaterfallCommandResult result=WaterfallCommands.AddConnector(s,O(s,0),B(s,1),true,"p0");
        Near(result.Solution.Columns[0].Base,-41);Near(result.Solution.Columns[1].Base,0);
        Check(result.ReleasedAutoPinId=="p0","Explicit alternate orientation respected");
    }
    private static void ManualConflict()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row(35));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,false);
        List<WaterfallConnector> links=s.Connectors;List<WaterfallPin> pins=s.Pins;
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),B(s,1));
        Check(analysis.AutoPinIds.Count==0,"Manual baselines never offered for removal");
        ExpectFailure(delegate{WaterfallCommands.AddConnector(s,O(s,0),B(s,1));},WaterfallSolveFailure.Inconsistent);
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,O(s,0),B(s,1),true,"p1");});
        Check(Object.ReferenceEquals(links,s.Connectors)&&Object.ReferenceEquals(pins,s.Pins),"Failed manual repair leaves exact source collections");
        WaterfallCommandResult free=WaterfallCommands.AddConnector(s,O(s,0),B(s,1),false);
        Check(free.Solution.Connectors[0].Skew && !free.Solution.Connectors[0].Constrained,"Explicit free connector preserves manual constraints");
        Near(free.Solution.Connectors[0].Residual,-41);
    }
    private static void PhysicalBaseline()
    {
        scenarios++;WaterfallSpec s=Spec(Row(5,-2));Pin(s,B(s,0),0,true);
        WaterfallScene scene=WaterfallScene.Build(s,640,360);
        WaterfallTarget target=scene.Targets.Find(delegate(WaterfallTarget t){return t.SegmentId=="s0_1"&&t.Edge=="Bottom";});
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzePinZero(s,target.Anchor);
        Check(analysis.AutoPinIds.Count==1&&analysis.AutoPinIds[0]=="p0","Mixed negative bottom has one generated-baseline repair");
        WaterfallCommandResult result=WaterfallCommands.PinZero(s,target.Anchor,"p0");
        WaterfallColumnSolution c=result.Solution.Columns[0];Near(c.Base,2);Near(c.Segments[1].Bottom,0);Near(c.Segments[0].Top,7);
        Check(s.Pins.Count==1&&!s.Pins[0].AutoGenerated&&s.Pins[0].Id==result.PinId,"Physical force becomes manual pin");
        Check(result.AffectedPinIds.Count==1&&result.AffectedPinIds[0]==result.PinId,"New manual pin reported");
    }
    private static void ExistingPinEdits()
    {
        scenarios++;WaterfallSpec s=Spec(Row(10));Pin(s,B(s,0),9,false);WaterfallPin previous=s.Pins[0];
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzePinZero(s,B(s,0));
        Check(analysis.StrictSucceeds&&s.Pins[0].Level==9,"Explicit same-anchor edit analyzed without mutation");
        WaterfallCommandResult result=WaterfallCommands.PinZero(s,B(s,0));
        Check(result.PinId=="p0"&&s.Pins.Count==1&&s.Pins[0].Level==0&&!s.Pins[0].AutoGenerated,"Manual level9 becomes0 retaining ID");
        Check(previous.Level==9,"Previously referenced pin object not mutated");Near(result.Solution.Columns[0].Base,0);
        s=Spec(Row(10));Pin(s,B(s,0),0,true);result=WaterfallCommands.PinZero(s,B(s,0));
        Check(result.PinId=="p0"&&!s.Pins[0].AutoGenerated,"Existing generated pin promoted, stable ID");
    }
    private static void TargetedDuplicates()
    {
        scenarios++;WaterfallSpec s=Spec(Row(10));Pin(s,B(s,0),9,true);Pin(s,B(s,0),9,false);
        WaterfallCommandResult result=WaterfallCommands.PinZero(s,B(s,0));
        Check(s.Pins.Count==2 && result.AffectedPinIds.Count==2,"Every identical target equation retained");
        Check(s.Pins[0].Id=="p0"&&s.Pins[1].Id=="p1"&&s.Pins[0].Level==0&&s.Pins[1].Level==0,"Duplicate stable IDs retained at requested zero");
        Check(!s.Pins[0].AutoGenerated&&!s.Pins[1].AutoGenerated,"All targeted equations now manual");
        s=Spec(Row(10));Pin(s,B(s,0),9,false);Pin(s,O(s,0),19,false);List<WaterfallPin> before=s.Pins;
        ExpectFailure(delegate{WaterfallCommands.PinZero(s,B(s,0));},WaterfallSolveFailure.Inconsistent);
        Check(Object.ReferenceEquals(before,s.Pins)&&s.Pins[0].Level==9&&s.Pins[1].Level==19,"Different manual anchor protected; targeted changes rollback");
    }
    private static void EqualsStaySymbolic()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row((double?)null));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,true);
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),O(s,1));
        Check(analysis.StrictSucceeds,"Adding constraint can determine previously free e");
        WaterfallCommandResult result=WaterfallCommands.AddConnector(s,O(s,0),O(s,1));Near(result.Solution.Columns[1].Segments[0].Value,41);
        Check(s.Columns[1].Segments[0].Calculated&&!s.Columns[1].Segments[0].Value.HasValue,"Calculated segment remains symbolic");
        result=WaterfallCommands.PinZero(s,B(s,1));Near(result.Solution.Columns[1].Segments[0].Value,41);
        Check(result.PinId=="p1"&&!s.Pins[1].AutoGenerated,"e baseline manualized without changing e definition");
    }
    private static void DuplicateConnectors()
    {
        scenarios++;WaterfallSpec s=Spec(Row(3),Row(3));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,false);Link(s,O(s,0),O(s,1));
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,O(s,0),O(s,1));});
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,O(s,1),O(s,0));});
        ExpectArgument(delegate{WaterfallCommands.AnalyzeAddConnector(s,O(s,1),O(s,0));});
        WaterfallCommandResult free=WaterfallCommands.AddConnector(s,O(s,1),O(s,0),false);
        Check(s.Connectors.Count==2&&s.Connectors[0].Id=="edge0"&&s.Connectors[1].Id==free.ConnectorId,"Different constraint mode allowed; existing ID stable");
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,O(s,0),O(s,1),false);});
    }
    private static void FailedRelease()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row(35),Row(1));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,true);Pin(s,B(s,2),0,true);
        List<WaterfallConnector> links=s.Connectors;List<WaterfallPin> pins=s.Pins;
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,O(s,0),B(s,1),true,"missing");});
        ExpectFailure(delegate{WaterfallCommands.AddConnector(s,O(s,0),B(s,1),true,"p2");},WaterfallSolveFailure.Inconsistent);
        Check(Object.ReferenceEquals(links,s.Connectors)&&Object.ReferenceEquals(pins,s.Pins)&&s.Pins.Count==3,"Failed chosen release is transactional");
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),B(s,1));
        Check(analysis.AutoPinIds.Count==1&&analysis.AutoPinIds[0]=="p1","Unrelated generated pin is not a candidate");
    }
    private static void NoUnnecessaryRelease()
    {
        scenarios++;WaterfallSpec s=Spec(Row(3),Row(3));Pin(s,B(s,0),0,true);Pin(s,B(s,1),0,true);
        WaterfallCommandResult result=WaterfallCommands.AddConnector(s,O(s,0),O(s,1),true,"p1");
        Check(result.ReleasedAutoPinId==null&&s.Pins.Count==2,"Strict success overrides unnecessary release request");
        result=WaterfallCommands.PinZero(s,B(s,0),"p1");
        Check(result.ReleasedAutoPinId==null&&s.Pins.Count==2&&s.Pins[1].AutoGenerated,"Pin edit also keeps unnecessary automatic pin");
    }
    private static void AnchorCopies()
    {
        scenarios++;WaterfallSpec s=Spec(Row(3),Row(3));Pin(s,B(s,0),0,false);Pin(s,B(s,1),0,false);
        WaterfallAnchor left=O(s,0),right=O(s,1);WaterfallCommands.AddConnector(s,left,right);left.Weights[0]=0;right.ColumnId="changed";
        Check(s.Connectors[0].Left.Weights[0]==1&&s.Connectors[0].Right.ColumnId=="c1","New connector owns copies of supplied anchors");
        WaterfallAnchor anchor=B(s,0);WaterfallCommands.PinZero(s,anchor);anchor.Weights[0]=1;
        Check(s.Pins[0].Anchor.Weights[0]==0,"Pin edit owns copy of supplied anchor");
    }
    private static void CandidateRequiresCompleteSolution()
    {
        scenarios++;WaterfallSpec s=Spec(Row(41),Row(35),Row((double?)null));Pin(s,B(s,0),0,true);Pin(s,B(s,1),0,true);Pin(s,B(s,2),0,true);
        WaterfallCommandAnalysis analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),B(s,1));
        Check(!analysis.StrictSucceeds&&analysis.AutoPinIds.Count==0,"Removing conflict alone is insufficient when an e remains undetermined");
        s=Spec(Row((double?)null),Row((double?)null));Pin(s,B(s,0),0,true);Pin(s,B(s,1),0,true);
        analysis=WaterfallCommands.AnalyzeAddConnector(s,O(s,0),O(s,1));
        Check(analysis.StrictFailure==WaterfallSolveFailure.Underdetermined&&analysis.AutoPinIds.Count==0,"Underdetermined equations never suggest pin removal");
    }
    private static void InvalidInputs()
    {
        scenarios++;WaterfallSpec s=Spec(Row(1));Pin(s,B(s,0),0,true);
        ExpectArgument(delegate{WaterfallCommands.PinZero(null,B(s,0));});
        ExpectArgument(delegate{WaterfallCommands.PinZero(s,null);});
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,B(s,0),WaterfallAnchor.ForWeights("unknown",0));});
        ExpectArgument(delegate{WaterfallCommands.AnalyzePinZero(s,WaterfallAnchor.ForWeights("c0",Double.NaN));});
        ExpectArgument(delegate{WaterfallCommands.AddConnector(s,B(s,0),WaterfallAnchor.ForWeights("c0",0,1));});
        Check(s.Pins.Count==1&&s.Connectors.Count==0,"Invalid commands leave model unchanged");
    }
    private static void ExpectFailure(Action action,WaterfallSolveFailure expected)
    {try{action();}catch(WaterfallSolveException ex){Check(ex.Failure==expected,"Expected constraint failure");return;}throw new Exception("Expected constraint failure");}
    private static void ExpectArgument(Action action)
    {try{action();}catch(ArgumentException){assertions++;return;}throw new Exception("Expected argument failure");}
    private static void Near(double a,double b){Check(Math.Abs(a-b)<1e-9,"Expected "+b+", got "+a);}
    private static void Check(bool condition,string message){assertions++;if(!condition)throw new Exception(message);}
}
